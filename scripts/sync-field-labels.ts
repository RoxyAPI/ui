#!/usr/bin/env bun
/**
 * Sync API labels into runtime locale modules and one build-only server form artifact.
 *
 * @remarks
 * **Build time, not run time, and that is the whole decision.** These labels translate request
 * field names that come from the OpenAPI spec, and the form already consumes that spec as
 * version-pinned artifacts baked at build. Fetching labels from the browser instead would buy no
 * decoupling the schema slices do not already have, and would cost three things that matter on an
 * embed: an extra request on the critical path, a dependency on the API being reachable for a
 * purely cosmetic payload, and a visible flash where every form paints English and then re-renders
 * translated a moment later. Baking them removes all three.
 *
 * @remarks
 * The keyless `/languages/field-labels?lang=` feed supplies all names, including `id.*` enums.
 * Shared fields and enums ride the existing `locales/{lang}.js` payload. Identifier picker names
 * and contextual operation/field labels are generated separately in `generated/form-labels.json`,
 * read only by build-forms.ts for server renderers. No browser entry imports that artifact.
 * `--from-disk` splits/rebuilds both outputs from persisted API names without another API read.
 * Refresh point is `bun run generate`, the same command that refreshes the spec.
 *
 * @remarks
 * A build with no reachable API keeps whatever is on disk and warns. That matters: the endpoint is
 * newer than this script, so a build running before the API ships must not fail, and a transient
 * outage must not silently blank a shipped catalogue.
 *
 * @remarks
 * `--check` is the drift gate: it regenerates every catalogue from the LIVE endpoint in memory and
 * fails when a committed module differs, so a label the API changed cannot ship stale from here.
 * It ignores the hermetic flag on purpose (drift is by definition between the live API and the
 * tree), and an unreachable API is a failure rather than a pass, because a check that passes when
 * it cannot check is the non-hermetic build with a hermetic name all over again. Output is
 * formatted through biome before writing or comparing, so the tree never shows a pure reformat as
 * a change and the comparison is byte-exact against what the hook would have committed.
 */
import { existsSync } from 'node:fs';
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import { API_LANGUAGES } from '../packages/ui/src/generated/api-languages.js';
import { EN_FIELD_LABELS } from '../packages/ui/src/generated/field-labels-en.js';
import {
	labelsFor,
	registerFieldLabels,
} from '../packages/ui/src/i18n/registry.js';
import {
	buildFormModel,
	type SpecDoc,
	translatedFieldLabel,
} from '../packages/ui/src/utils/field-schema.js';
import { humanize } from '../packages/ui/src/utils/string.js';

const API_BASE = process.env.ROXY_API_BASE ?? 'https://roxyapi.com/api/v2';
const LOCALES_DIR = 'packages/ui/src/locales';
const OUT_DIR = `${LOCALES_DIR}/field-labels`;
/** English ships no payload, so the API English names the form prints are compiled in, and only where they differ from what `humanize` would print anyway. */
const EN_OUT = 'packages/ui/src/generated/field-labels-en.ts';
const SERVER_OUT = 'packages/ui/src/generated/form-labels.json';

interface ServerLabels {
	enums: Record<string, string>;
	labels: Record<string, string>;
}

/**
 * Derived twice over, never mirrored by hand: a language the API serves AND ships a chrome
 * payload for. English is absent because it needs no payload.
 *
 * @remarks
 * A hand-kept copy is checked against itself, and the language somebody forgets to add to it is
 * the one that then ships with unlabelled fields and no error anywhere (lesson 23). `lang` on the
 * spec is the only place the set of API languages is decided, so read it from there.
 *
 * The second half is the directory, because a labels module is imported by its language's chrome
 * payload and by nothing else: written for a language with no payload it is unreachable code that
 * ships in the tarball and no build reports. The set the API serves can therefore run ahead of the
 * set catalogued here, which it does whenever a language lands upstream before its chrome does.
 * `tests/i18n.test.ts` is what stops that drifting silently: it holds this directory to the
 * shipped catalogues, and holds the shipped catalogues to the API's own list bar a declared
 * exception per language.
 */
const CATALOGUED = new Set(
	(await readdir(LOCALES_DIR))
		.filter((f) => f.endsWith('.ts'))
		.map((f) => f.replace(/\.ts$/, '')),
);
const LANGS = API_LANGUAGES.filter((l) => l !== 'en' && CATALOGUED.has(l));

interface LabelPayload {
	fields?: Record<string, string>;
	enums?: Record<string, string>;
}

function emit(lang: string, payload: LabelPayload): string {
	const fields = JSON.stringify(payload.fields ?? {}, null, '\t');
	const enums = JSON.stringify(payload.enums ?? {}, null, '\t');
	return `/**
 * GENERATED by \`bun run scripts/sync-field-labels.ts\`. Do not edit.
 *
 * @remarks
 * Labels for request field names and their selectable options, in ${lang}. Importing this module
 * registers them and re-renders every mounted form, exactly like the chrome catalogue beside it.
 * Regenerate with \`bun run generate\`; the source of truth is the API, not this file.
 */

import { registerFieldLabels } from '../../i18n/registry.js';

registerFieldLabels('${lang}', {
\tfields: ${fields.replace(/\n/g, '\n\t')},
\tenums: ${enums.replace(/\n/g, '\n\t')},
});
`;
}

/** The API English label of every field whose label is not simply its humanized name, sorted for a stable diff. */
function emitEnglish(payload: LabelPayload): string {
	const differing = Object.entries(payload.fields ?? {})
		.filter(([name, label]) => label !== humanize(name))
		.sort(([a], [b]) => a.localeCompare(b));
	return `/**
 * GENERATED by \`bun run scripts/sync-field-labels.ts\`. Do not edit.
 *
 * @remarks
 * The API English label of every request field whose label differs from its humanized wire name, which the form prints on an English page and wherever a translated payload carries no label of its own.
 */
export const EN_FIELD_LABELS: Record<string, string> = ${JSON.stringify(Object.fromEntries(differing), null, '\t')};
`;
}

/** Every catalogue this script writes: one per shipped language plus the compiled-in English override. */
const TARGETS = [
	...LANGS.map((lang) => ({
		lang,
		out: `${OUT_DIR}/${lang}.ts`,
		emit: (p: LabelPayload) => emit(lang, p),
	})),
	{ lang: 'en', out: EN_OUT, emit: emitEnglish },
];

const CHECK = process.argv.includes('--check');

/** The generated text as biome commits it, so a diff is content and never formatting. */
function formatted(path: string, text: string): string {
	const run = Bun.spawnSync(
		['bun', 'x', 'biome', 'format', `--stdin-file-path=${path}`],
		{
			stdin: Buffer.from(text),
		},
	);
	if (run.exitCode !== 0)
		throw new Error(`biome format failed: ${run.stderr.toString()}`);
	return run.stdout.toString();
}

export async function fetchLabels(lang: string): Promise<LabelPayload> {
	const res = await fetch(`${API_BASE}/languages/field-labels?lang=${lang}`, {
		signal: AbortSignal.timeout(20_000),
	});
	if (!res.ok) throw new Error(`HTTP ${res.status}`);
	const body = (await res.json()) as LabelPayload;
	if (!body.fields || Object.keys(body.fields).length === 0) {
		throw new Error('payload carried no fields');
	}
	return body;
}

/** Separate build-only picker names by their existing key space, keeping shared enums intact. */
export function splitLabelPayload(payload: LabelPayload): {
	runtime: LabelPayload;
	server: ServerLabels;
} {
	const runtimeEnums: Record<string, string> = {};
	const pickerEnums: Record<string, string> = {};
	for (const [key, label] of Object.entries(payload.enums ?? {})) {
		(key.startsWith('id.') ? pickerEnums : runtimeEnums)[key] = label;
	}
	return {
		runtime: { fields: payload.fields ?? {}, enums: runtimeEnums },
		server: { enums: pickerEnums, labels: {} },
	};
}

/** Both outputs derive from one synced payload; contextual labels never enter a runtime module. */
async function labelOutputs(
	lang: string,
	payload: LabelPayload,
	spec: SpecDoc,
) {
	const { runtime, server } = splitLabelPayload(payload);
	if (lang !== 'en') await import(`../packages/ui/src/locales/${lang}.js`);
	registerFieldLabels(lang, {
		fields: runtime.fields ?? {},
		enums: runtime.enums ?? {},
	});
	for (const [path, item] of Object.entries(spec.paths)) {
		for (const [method, op] of Object.entries(item)) {
			if (!op.operationId) continue;
			for (const field of buildFormModel(
				op,
				spec.components?.schemas ?? {},
				path,
				method,
			).fields) {
				if (!field.label) continue;
				const label =
					lang === 'en' ? field.label : translatedFieldLabel(lang, field);
				if (label !== undefined)
					server.labels[`${op.operationId}.${field.key}`] = label;
			}
		}
	}
	return { runtime, server };
}

async function main() {
	// Replay persisted API names for migrations/offline rebuilds without another API read.
	const fromDisk = process.argv.includes('--from-disk');
	if (CHECK && fromDisk)
		throw new Error(
			'--check requires live API reads; it cannot use --from-disk',
		);
	if (!CHECK && !fromDisk && process.env.ROXYAPI_SPEC_FILE) {
		console.log(
			`Keeping runtime and server form labels (offline, ROXYAPI_SPEC_FILE)`,
		);
		return;
	}
	await mkdir(OUT_DIR, { recursive: true });
	const spec = (await Bun.file('specs/openapi.json').json()) as SpecDoc;
	const serverLabels: Record<string, ServerLabels> = existsSync(SERVER_OUT)
		? await Bun.file(SERVER_OUT).json()
		: {};
	const drifted: string[] = [];
	let written = 0;
	let kept = 0;
	for (const { lang, out, emit: write } of TARGETS) {
		try {
			let payload: LabelPayload;
			if (fromDisk) {
				if (lang === 'en')
					payload = {
						fields: EN_FIELD_LABELS,
						enums: serverLabels.en?.enums ?? {},
					};
				else {
					await import(`../${OUT_DIR}/${lang}.ts`);
					const existing = labelsFor(lang);
					if (!existing)
						throw new Error(`No persisted field labels for ${lang}`);
					payload = {
						fields: existing.fields,
						enums: { ...existing.enums, ...serverLabels[lang]?.enums },
					};
				}
			} else payload = await fetchLabels(lang);
			const outputs = await labelOutputs(lang, payload, spec);
			const expected = formatted(out, write(outputs.runtime));
			if (CHECK) {
				const committed = existsSync(out) ? await Bun.file(out).text() : '';
				if (committed !== expected) drifted.push(lang);
			} else await writeFile(out, expected);
			serverLabels[lang] = outputs.server;
			written++;
		} catch (err) {
			if (CHECK || fromDisk) throw err;
			if (!existsSync(out)) throw err;
			console.warn(
				`${lang}: ${String(err)} — keeping both committed label outputs`,
			);
			kept++;
		}
	}
	const serverText = formatted(
		SERVER_OUT,
		JSON.stringify(serverLabels, null, '\t'),
	);
	if (CHECK) {
		if (
			!existsSync(SERVER_OUT) ||
			(await Bun.file(SERVER_OUT).text()) !== serverText
		)
			drifted.push('server forms');
		if (drifted.length)
			throw new Error(
				`Field labels drifted from the live API: ${drifted.join(', ')}. Run 'bun run labels:sync'.`,
			);
		console.log(
			`Runtime and server form labels match the live API across ${TARGETS.length} catalogue(s).`,
		);
	} else {
		await writeFile(SERVER_OUT, serverText);
		console.log(
			`Field labels: ${written} runtime/server pairs written, ${kept} kept from disk. Server labels: ${SERVER_OUT}`,
		);
	}
}

if (import.meta.main) await main();
